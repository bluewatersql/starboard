"""Generate the agent-experience capability catalog from live sources (Task E2, D-3.1).

Usage::

    python scripts/gen_catalog.py           # generate the catalog + per-surface index pages
    python scripts/gen_catalog.py --check    # exit 1 if any committed page is stale

Output
------
``docs/reference/CATALOG.md`` — the top-level capability index, plus one
``INDEX.md`` per surface under ``docs/reference/{skills,mcp-tools,agents,
cli-commands,progressive-helpers,plugins}/``.

Why generate
------------
The *surface lists* (which skills/tools/agents/CLI-commands/helpers/plugins
exist) are read from the live sources so they can never drift from the shipped
code (D-3.1). Hand-authored prose (the "how to choose" guide, hero workflows)
lives in separate, non-generated files.

Live sources
------------
- MCP tools     — ``ALL_TOOL_METADATA`` in ``starboard.agents.tools.registry``.
                  The authoritative tool count is ``len(ALL_TOOL_METADATA)``
                  (D-3.2). Tools are *shared* across agents; the catalog states
                  the registry count and never publishes the inflated
                  per-agent sum.
- Skills        — ``packages/starboard-skills/skills/starboard/*/SKILL.md``.
- Agents        — ``packages/starboard-skills/agents/*.yaml``.
- CLI commands  — the routed command groups in ``starboard.cli.cli.main`` /
                  ``review_command`` / ``auth_commands``.
- Helpers       — ``starboard_x.__main__._IMPLEMENTED`` / ``_DECLARED``
                  (``python -m starboard_x.<cap>``).
- Plugins       — the ``starboard.mcp_tools`` entry-point contract + the sample
                  plugin package.

Every generated page starts with a ``GENERATED`` marker comment so the source
of truth is unambiguous.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from importlib import import_module
from pathlib import Path

# ---------------------------------------------------------------------------
# Repo-root resolution (walk up until the canonical skills package is found)
# ---------------------------------------------------------------------------


def _repo_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "packages" / "starboard-skills" / "skills").is_dir():
            return parent
    raise AssertionError("Cannot locate repo root (expected packages/starboard-skills/skills/)")


REPO_ROOT = _repo_root()
SKILLS_ROOT = REPO_ROOT / "packages" / "starboard-skills" / "skills" / "starboard"
AGENTS_ROOT = REPO_ROOT / "packages" / "starboard-skills" / "agents"
REFERENCE_DIR = REPO_ROOT / "docs" / "reference"

GENERATED_MARKER = (
    "<!-- GENERATED by scripts/gen_catalog.py — DO NOT EDIT. "
    "Regenerate: python scripts/gen_catalog.py -->"
)

# Per-surface index pages, keyed by the sub-directory under docs/reference/.
SURFACES: tuple[str, ...] = (
    "skills",
    "mcp-tools",
    "agents",
    "cli-commands",
    "progressive-helpers",
    "plugins",
)

# ---------------------------------------------------------------------------
# Markdown-cell sanitisation
# ---------------------------------------------------------------------------

_FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---", re.DOTALL)


def _cell(text: str) -> str:
    """Sanitise *text* for use inside a single Markdown table cell.

    Keeps only the first non-empty line, escapes pipes (which would otherwise
    split the cell), collapses whitespace, and neutralises Jinja delimiters so
    the mkdocs-macros plugin cannot try to render registry-supplied prose.
    """
    first = ""
    for line in text.splitlines():
        if line.strip():
            first = line.strip()
            break
    first = re.sub(r"\s+", " ", first)
    first = first.replace("|", r"\|")
    first = first.replace("{{", "{ {").replace("}}", "} }")
    first = first.replace("{%", "{ %").replace("%}", "% }")
    return first


def _read_frontmatter(md_path: Path) -> dict[str, object]:
    """Return the parsed YAML frontmatter of a Markdown file (empty on miss)."""
    import yaml

    text = md_path.read_text(encoding="utf-8")
    m = _FRONTMATTER_RE.match(text)
    if not m:
        return {}
    return yaml.safe_load(m.group(1)) or {}


# ---------------------------------------------------------------------------
# Surface collectors — each reads a live source and returns sorted entries
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SkillEntry:
    name: str
    description: str
    directory: str


@dataclass(frozen=True)
class ToolEntry:
    name: str
    summary: str
    required: tuple[str, ...]


@dataclass(frozen=True)
class AgentEntry:
    name: str
    kind: str
    domain: str
    mcp_tool: str
    skill_ref: str
    description: str


@dataclass(frozen=True)
class CliEntry:
    command: str
    purpose: str
    invocation: str
    dispatch: str  # importable "module:symbol" that routes the command


@dataclass(frozen=True)
class HelperEntry:
    name: str
    invocation: str
    implemented: bool
    module: str


@dataclass(frozen=True)
class PluginEntry:
    entry_point_group: str
    sample_package: str
    contract: str


def collect_skills() -> list[SkillEntry]:
    """Read every ``SKILL.md`` under the canonical skills tree."""
    entries: list[SkillEntry] = []
    for skill_md in sorted(SKILLS_ROOT.glob("*/SKILL.md")):
        fm = _read_frontmatter(skill_md)
        entries.append(
            SkillEntry(
                name=str(fm.get("name", skill_md.parent.name)),
                description=str(fm.get("description", "")),
                directory=skill_md.parent.name,
            )
        )
    return sorted(entries, key=lambda e: e.name)


def collect_tools() -> list[ToolEntry]:
    """Read the live MCP-tool registry (``ALL_TOOL_METADATA``)."""
    registry = import_module("starboard.agents.tools.registry")
    all_meta: dict[str, dict[str, object]] = registry.ALL_TOOL_METADATA
    entries: list[ToolEntry] = []
    for name, meta in all_meta.items():
        params = meta.get("parameters") or {}
        required = params.get("required", []) if isinstance(params, dict) else []
        entries.append(
            ToolEntry(
                name=name,
                summary=str(meta.get("description", "")),
                required=tuple(str(r) for r in required),
            )
        )
    return sorted(entries, key=lambda e: e.name)


def collect_agents() -> list[AgentEntry]:
    """Read every canonical agent definition (``agents/*.yaml``)."""
    import yaml

    entries: list[AgentEntry] = []
    for yaml_path in sorted(AGENTS_ROOT.glob("*.yaml")):
        data = yaml.safe_load(yaml_path.read_text(encoding="utf-8")) or {}
        entries.append(
            AgentEntry(
                name=str(data.get("name", yaml_path.stem)),
                kind=str(data.get("kind", "")),
                domain=str(data.get("domain", "")),
                mcp_tool=str(data.get("mcp_tool") or "—"),
                skill_ref=str(data.get("skill_ref", "")),
                description=str(data.get("description", "")),
            )
        )
    return sorted(entries, key=lambda e: e.name)


def collect_cli_commands() -> list[CliEntry]:
    """Enumerate the CLI command surface.

    Each entry names the importable dispatch symbol that routes the command in
    ``starboard.cli.cli.main.main``; :func:`_verify_cli_dispatch` imports them
    so a renamed/removed route fails generation instead of drifting silently.
    """
    return [
        CliEntry(
            command="starboard --goal / --chat",
            purpose="Natural-language goal agent (multi-agent loop) and interactive chat.",
            invocation='starboard --goal "<request>"  ·  starboard --chat',
            dispatch="starboard.cli.cli.main:parse_args",
        ),
        CliEntry(
            command="starboard --discover",
            purpose="Non-agentic workspace discovery and health assessment.",
            invocation="starboard --discover",
            dispatch="starboard.cli.cli.main:run_discovery_mode",
        ),
        CliEntry(
            command="starboard review",
            purpose="Workload Review over public system.* data (severity gate).",
            invocation="starboard review [--domains jobs,sql,warehouse]",
            dispatch="starboard.cli.cli.review_command:run_review",
        ),
        CliEntry(
            command="starboard auth",
            purpose="Auth-by-subtraction helpers (login / status) over the SDK credential chain.",
            invocation="starboard auth login  ·  starboard auth status",
            dispatch="starboard.cli.cli.auth_commands:run_auth",
        ),
    ]


def collect_helpers() -> list[HelperEntry]:
    """Read the live progressive-helper dispatch table from ``starboard_x``."""
    dispatcher = import_module("starboard_x.__main__")
    implemented: dict[str, str] = dict(dispatcher._IMPLEMENTED)
    declared: tuple[str, ...] = tuple(dispatcher._DECLARED)
    entries: list[HelperEntry] = []
    for name, module in implemented.items():
        entries.append(
            HelperEntry(
                name=name,
                invocation=f"python -m starboard_x.{name}",
                implemented=True,
                module=module.rsplit(".", 1)[0],
            )
        )
    for name in declared:
        entries.append(
            HelperEntry(
                name=name,
                invocation=f"python -m starboard_x.{name}",
                implemented=False,
                module=f"starboard_x.{name}",
            )
        )
    return sorted(entries, key=lambda e: e.name)


def collect_plugins() -> PluginEntry:
    """Describe the opt-in per-domain plugin contract + the sample package."""
    return PluginEntry(
        entry_point_group="starboard.mcp_tools",
        sample_package="starboard-plugin-sample",
        contract="starboard.tools.plugins.ToolPlugin",
    )


# ---------------------------------------------------------------------------
# Dispatch verification (fail generation on a dead CLI route)
# ---------------------------------------------------------------------------


def _verify_cli_dispatch(entries: list[CliEntry]) -> None:
    for entry in entries:
        module_name, _, symbol = entry.dispatch.partition(":")
        module = import_module(module_name)
        if not hasattr(module, symbol):
            raise AssertionError(
                f"CLI dispatch symbol not found: {entry.dispatch} "
                f"(command {entry.command!r})"
            )


