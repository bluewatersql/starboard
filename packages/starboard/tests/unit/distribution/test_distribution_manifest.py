"""Unit tests for the aitools distribution mirror and manifest.

Validates that:
1. The generated mirror matches the canonical skills roster.
2. The manifest.json conforms to its declared schema.
3. Every skill in the mirror has valid frontmatter (per the Agent Skills spec
   and the ai-dev-kit validate_skills.py rules — agentskills.io/specification).
4. Regenerating the mirror (``python scripts/skills.py``) is idempotent: skill
   file content is stable across runs (``generated_at`` in manifest.json changes
   per-run by design and is excluded from the stability check).

These tests ride ``make test-unit`` (CI-collected) and are deliberately
side-effect-free: they read from the committed mirror + manifest, do NOT
execute the generation script (test #4 uses filecmp, not a subprocess), and
therefore impose no network or filesystem write requirements in CI.

The committed mirror at ``packages/starboard-distribution/aitools/`` is
generated by ``python scripts/skills.py`` and must be regenerated whenever the
canonical skills tree changes.  Run ``make test-distribution`` (see note in
reports) to detect drift.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest
import yaml

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

def _repo_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "packages" / "starboard-skills" / "skills").is_dir():
            return parent
    raise AssertionError(
        "could not locate repo root containing packages/starboard-skills/skills"
    )


REPO_ROOT = _repo_root()
CANONICAL_SKILLS_ROOT = REPO_ROOT / "packages" / "starboard-skills" / "skills" / "starboard"
MIRROR_ROOT = REPO_ROOT / "packages" / "starboard-distribution" / "aitools"
MANIFEST_PATH = MIRROR_ROOT / "manifest.json"


def _load_skill_transform():
    """Load scripts/skill_transform.py (the shared host-portability transform)."""
    script = REPO_ROOT / "scripts" / "skill_transform.py"
    spec = importlib.util.spec_from_file_location("skill_transform_under_test", script)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


_XFORM = _load_skill_transform()
_COMMAND_MAP = _XFORM.build_command_map(CANONICAL_SKILLS_ROOT)

# Expected roster from the canonical tree (adds the `engagement` scaffold skill)
EXPECTED_SKILL_COUNT = 13

# ---------------------------------------------------------------------------
# Agent Skills spec constraints (agentskills.io/specification) —
# same rules enforced by ai-dev-kit validate_skills.py
# ---------------------------------------------------------------------------

_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
_XML_TAG_RE = re.compile(r"<[^>]+>")
_RESERVED_WORDS = {"anthropic", "claude"}
NAME_MAX = 64
DESCRIPTION_MAX = 1024
_FRONTMATTER_RE = re.compile(r"\A---\r?\n(?P<yaml>.*?)\r?\n---\r?\n", re.DOTALL)


def _parse_frontmatter(text: str) -> dict:
    match = _FRONTMATTER_RE.match(text)
    assert match is not None, "SKILL.md must open with fenced YAML frontmatter"
    data = yaml.safe_load(match.group("yaml"))
    assert isinstance(data, dict), "frontmatter must parse to a YAML mapping"
    return data


def _canonical_skill_names() -> list[str]:
    if not CANONICAL_SKILLS_ROOT.is_dir():
        return []
    return sorted(p.name for p in CANONICAL_SKILLS_ROOT.iterdir() if p.is_dir())


def _mirror_skill_names() -> list[str]:
    if not MIRROR_ROOT.is_dir():
        return []
    return sorted(
        p.name
        for p in MIRROR_ROOT.iterdir()
        if p.is_dir()
    )


# ---------------------------------------------------------------------------
# Manifest schema tests
# ---------------------------------------------------------------------------

def test_manifest_exists() -> None:
    """manifest.json must exist in the mirror root."""
    assert MANIFEST_PATH.exists(), (
        f"manifest.json not found at {MANIFEST_PATH} — "
        "run: python scripts/skills.py"
    )


def test_manifest_valid_json() -> None:
    """manifest.json must be valid JSON."""
    text = MANIFEST_PATH.read_text(encoding="utf-8")
    manifest = json.loads(text)  # raises on invalid JSON
    assert isinstance(manifest, dict)


def test_manifest_required_keys() -> None:
    """manifest.json must contain the required top-level keys."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    required = {"schema_version", "bundle_name", "bundle_version", "skills", "format"}
    missing = required - set(manifest)
    assert not missing, f"manifest.json missing required keys: {sorted(missing)}"


def test_manifest_schema_version() -> None:
    """schema_version must be '1.0'."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    assert manifest["schema_version"] == "1.0", (
        f"unexpected schema_version: {manifest['schema_version']!r}"
    )


def test_manifest_bundle_name() -> None:
    """bundle_name must be 'starboard'."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    assert manifest["bundle_name"] == "starboard"


def test_manifest_format_field() -> None:
    """format must be 'agent-skills'."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    assert manifest["format"] == "agent-skills"


def test_manifest_skills_count() -> None:
    """manifest.json must list exactly EXPECTED_SKILL_COUNT skills."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    skills = manifest.get("skills", [])
    assert isinstance(skills, list)
    assert len(skills) == EXPECTED_SKILL_COUNT, (
        f"expected {EXPECTED_SKILL_COUNT} skills in manifest, found {len(skills)}"
    )


def test_manifest_matches_canonical_roster() -> None:
    """Every canonical skill is in the manifest and no phantom entries exist."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    manifest_names = {s["name"] for s in manifest.get("skills", [])}
    canonical_names = set(_canonical_skill_names())
    missing = canonical_names - manifest_names
    extra = manifest_names - canonical_names
    assert not missing, f"skills missing from manifest: {sorted(missing)}"
    assert not extra, f"manifest has unknown skills (not in canonical tree): {sorted(extra)}"


def test_manifest_skill_entries_have_required_fields() -> None:
    """Each skill entry must have 'name', 'path', and 'description'."""
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    for skill in manifest.get("skills", []):
        name = skill.get("name", "<unknown>")
        assert "name" in skill, f"skill entry missing 'name': {skill}"
        assert "path" in skill, f"{name}: skill entry missing 'path'"
        assert "description" in skill, f"{name}: skill entry missing 'description'"
        # path must point to the skill subdirectory
        assert skill["path"] == f"{skill['name']}/", (
            f"{name}: 'path' should be '{skill['name']}/', got {skill['path']!r}"
        )


