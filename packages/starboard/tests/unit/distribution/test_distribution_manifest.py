@pytest.mark.parametrize("skill_dir_name", _canonical_skill_names())
def test_mirror_skill_files_match_canonical(skill_dir_name: str) -> None:
    """Each mirrored file must equal the *host-neutral transform* of its source.

    The aitools mirror is an ADAPTED copy of the canonical tree (the
    Claude-Code-only ``${CLAUDE_SKILL_DIR}/scripts/run.sh`` invocation is
    rewritten to the portable ``python -m starboard_x.<cap>`` / ``starboard``
    command — see ``scripts/skill_transform.py``), so this checks the mirror
    against that expected transform, not the raw canonical bytes.  The full
    regenerate-and-diff is in ``make test-distribution``; this parametrized
    form catches regressions at the per-skill level in ``make test-unit``.
    """
    canonical_dir = CANONICAL_SKILLS_ROOT / skill_dir_name
    mirror_dir = MIRROR_ROOT / skill_dir_name

    canonical_files = {
        p.relative_to(canonical_dir).as_posix()
        for p in canonical_dir.rglob("*")
        if p.is_file()
    }
    mirror_files = {
        p.relative_to(mirror_dir).as_posix()
        for p in mirror_dir.rglob("*")
        if p.is_file()
    }

    missing = canonical_files - mirror_files
    extra = mirror_files - canonical_files
    assert not missing, f"{skill_dir_name}: files missing from mirror: {sorted(missing)}"
    assert not extra, f"{skill_dir_name}: stale files in mirror: {sorted(extra)}"

    command = _XFORM.command_for(skill_dir_name, _COMMAND_MAP)
    differing = {
        rel
        for rel in canonical_files & mirror_files
        if (mirror_dir / rel).read_bytes()
        != _XFORM.transform_file_bytes(
            canonical_dir / rel, (canonical_dir / rel).read_bytes(), command
        )
    }
    assert not differing, (
        f"{skill_dir_name}: mirror files differ from the expected transform: "
        f"{sorted(differing)}\nRun: python scripts/skills.py"
    )


@pytest.mark.parametrize("skill_dir_name", _canonical_skill_names())
def test_mirror_has_no_claude_skill_dir_token(skill_dir_name: str) -> None:
    """The adapted mirror must not ship the Claude-Code-only run.sh token."""
    mirror_dir = MIRROR_ROOT / skill_dir_name
    offenders = [
        p.relative_to(MIRROR_ROOT).as_posix()
        for p in mirror_dir.rglob("*")
        if p.is_file()
        and p.suffix in {".md", ".sh"}
        and "CLAUDE_SKILL_DIR" in p.read_text(encoding="utf-8")
    ]
    assert not offenders, (
        f"{skill_dir_name}: mirror still contains ${{CLAUDE_SKILL_DIR}} in "
        f"{offenders} — the host-neutral transform did not run"
    )


# ---------------------------------------------------------------------------
# check() tolerates vendor()-preserved non-skill root files (drift-guard fix)
# ---------------------------------------------------------------------------

class TestCheckToleratesPreservedRootFiles:
    """`skills.check()` must agree with `skills.vendor()` on preserved files.

    vendor() (re)generates manifest.json and deliberately preserves any other
    top-level file in the mirror root; check() must therefore not report such a
    file as drift, while still catching real drift inside a skill directory.
    """

    @staticmethod
    def _load_skills_module():
        import importlib.util

        script = REPO_ROOT / "scripts" / "skills.py"
        spec = importlib.util.spec_from_file_location("skills_script_under_test", script)
        assert spec and spec.loader
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod

    @staticmethod
    def _setup(tmp_path: Path) -> tuple[Path, Path, Path]:
        skill_md = "---\nname: starboard-demo\ndescription: demo\n---\n\nBody.\n"
        canonical = tmp_path / "canonical"
        (canonical / "starboard-demo").mkdir(parents=True)
        (canonical / "starboard-demo" / "SKILL.md").write_text(skill_md)

        mirror = tmp_path / "mirror"
        (mirror / "starboard-demo").mkdir(parents=True)
        (mirror / "starboard-demo" / "SKILL.md").write_text(skill_md)
        manifest = mirror / "manifest.json"
        manifest.write_text(
            json.dumps(
                {
                    "schema_version": "1.0",
                    "bundle_name": "starboard",
                    "skills": [{"name": "starboard-demo", "path": "starboard-demo/"}],
                }
            )
        )
        return canonical, mirror, manifest

    def test_preserved_root_file_is_not_drift(self, tmp_path, monkeypatch) -> None:
        mod = self._load_skills_module()
        canonical, mirror, manifest = self._setup(tmp_path)
        (mirror / "README.md").write_text("# aitools bundle\n")  # vendor preserves this

        monkeypatch.setattr(mod, "CANONICAL_SKILLS", canonical)
        monkeypatch.setattr(mod, "MIRROR_ROOT", mirror)
        monkeypatch.setattr(mod, "MANIFEST_PATH", manifest)

        assert mod.check() == 0, "check() falsely flagged a preserved root file as drift"

    def test_stale_file_inside_skill_dir_is_still_drift(self, tmp_path, monkeypatch) -> None:
        mod = self._load_skills_module()
        canonical, mirror, manifest = self._setup(tmp_path)
        (mirror / "starboard-demo" / "STALE.md").write_text("stale\n")

        monkeypatch.setattr(mod, "CANONICAL_SKILLS", canonical)
        monkeypatch.setattr(mod, "MIRROR_ROOT", mirror)
        monkeypatch.setattr(mod, "MANIFEST_PATH", manifest)

        assert mod.check() == 1, "check() missed a genuinely stale skill file"
