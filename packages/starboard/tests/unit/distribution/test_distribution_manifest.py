# ---------------------------------------------------------------------------
# Frontmatter validation tests (Agent Skills spec + ai-dev-kit rules)
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("skill_dir_name", _canonical_skill_names())
def test_mirror_frontmatter_name_valid(skill_dir_name: str) -> None:
    """name field: required, ≤64 chars, lowercase alnum+hyphens, no XML, matches dir."""
    skill_md = MIRROR_ROOT / skill_dir_name / "SKILL.md"
    fm = _parse_frontmatter(skill_md.read_text(encoding="utf-8"))
    name = fm.get("name")
    assert name, f"{skill_dir_name}: 'name' is required"
    name = str(name)
    assert len(name) <= NAME_MAX, f"{skill_dir_name}: name exceeds {NAME_MAX} chars"
    assert _NAME_RE.match(name), (
        f"{skill_dir_name}: name '{name}' must be lowercase alnum + single hyphens"
    )
    assert not _XML_TAG_RE.search(name), f"{skill_dir_name}: name must not contain XML tags"
    for word in _RESERVED_WORDS:
        assert word not in name, (
            f"{skill_dir_name}: name must not contain reserved word '{word}'"
        )
    assert name == skill_dir_name, (
        f"{skill_dir_name}: spec requires name == directory name (got '{name}')"
    )


@pytest.mark.parametrize("skill_dir_name", _canonical_skill_names())
def test_mirror_frontmatter_description_valid(skill_dir_name: str) -> None:
    """description field: required, non-empty, ≤1024 chars, no XML."""
    skill_md = MIRROR_ROOT / skill_dir_name / "SKILL.md"
    fm = _parse_frontmatter(skill_md.read_text(encoding="utf-8"))
    desc = fm.get("description")
    assert desc and str(desc).strip(), f"{skill_dir_name}: 'description' is required and non-empty"
    desc = str(desc)
    assert len(desc) <= DESCRIPTION_MAX, (
        f"{skill_dir_name}: description exceeds {DESCRIPTION_MAX} chars ({len(desc)})"
    )
    assert not _XML_TAG_RE.search(desc), (
        f"{skill_dir_name}: description must not contain XML tags"
    )


