"""Unit tests for the agent-experience catalog generator (Task E2, D-3.1).

Validates:
- ``gen_catalog.py --check`` passes on the committed output (regenerate-and-diff,
  mirroring ``test_gen_rulesets.py``).
- Every catalogued surface resolves to a real thing: skills → skill dir,
  agents → canonical YAML, tools → ``ALL_TOOL_METADATA`` key, helpers →
  importable module, CLI commands → importable dispatch symbol.
- The tool count equals ``len(ALL_TOOL_METADATA)`` (D-3.2), with no dead
  references in the committed MCP-tools page.
- Governance: no internal namespaces on any generated page or the guide.
- Every generated page is wired into the mkdocs nav.
"""

