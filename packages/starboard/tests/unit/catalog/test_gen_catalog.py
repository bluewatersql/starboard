_SCRIPTS_DIR = _REPO_ROOT / "scripts"
_GENERATOR = _SCRIPTS_DIR / "gen_catalog.py"
_REFERENCE_DIR = _REPO_ROOT / "docs" / "reference"
_SKILLS_DIR = _REPO_ROOT / "packages" / "starboard-skills" / "skills" / "starboard"
