_GOVERNED_FILES = _EXPECTED_PAGES + [_REPO_ROOT / "docs" / "guides" / "AGENT_EXPERIENCE.md"]


@pytest.mark.parametrize("path", _GOVERNED_FILES, ids=lambda p: str(p.name))
def test_no_internal_namespaces(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    for ns in _INTERNAL_NAMESPACES:
        assert ns not in text, f"{path.name}: contains internal namespace {ns!r}"


# ---------------------------------------------------------------------------
# mkdocs nav wiring (strict build requires every page in nav)
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("page", _EXPECTED_PAGES + [_REPO_ROOT / "docs" / "guides" / "AGENT_EXPERIENCE.md"],
                         ids=lambda p: str(p.name))
def test_page_wired_into_nav(page: Path) -> None:
    nav_ref = str(page.relative_to(_REPO_ROOT / "docs"))
    mkdocs = _MKDOCS.read_text(encoding="utf-8")
    assert nav_ref in mkdocs, f"{nav_ref} is not referenced in mkdocs.yml nav"
